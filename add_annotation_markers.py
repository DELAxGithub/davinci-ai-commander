def run(dry_run=False, color="Green", fps=0):
    """
    DaVinci Resolve コンソールから直接呼べるエントリポイント。

    使い方（コンソール）:
      exec(open("/Users/delaxstudio/src/davinci-ai-commander/add_annotation_markers.py").read())
      run()              # マーカー挿入
      run(dry_run=True)  # 確認のみ
      run(color="Yellow") # 色変更
    """
    # Resolve 接続
    resolve = None
    if not dry_run:
        resolve = load_resolve()
        if not resolve:
            print("ERROR: DaVinci Resolve に接続できません。run(dry_run=True) で確認できます。")
            return

    # FPS 取得
    if fps == 0 and resolve:
        project = resolve.GetProjectManager().GetCurrentProject()
        timeline = project.GetCurrentTimeline()
        fps_str = timeline.GetSetting("timelineFrameRate")
        fps = float(fps_str) if fps_str else 59.94
        print(f"タイムラインFPS: {fps}")
    elif fps == 0:
        fps = 59.94
        print(f"デフォルトFPS: {fps}")

    # タイムライン取得
    timeline = None
    start_frames = 0
    if resolve:
        project = resolve.GetProjectManager().GetCurrentProject()
        timeline = project.GetCurrentTimeline()
        tl_name = timeline.GetName()
        start_tc = timeline.GetStartTimecode()
        start_frames = tc_to_frames(start_tc, fps)
        print(f"タイムライン: {tl_name}")
        print(f"タイムライン開始TC: {start_tc}")

    # マーカー生成
    marker_count = 0
    errors = []

    for case_num, rel_tc, name, note in ANNOTATIONS:
        if case_num not in CASE_OFFSETS:
            errors.append(f"Case{case_num} のオフセットが未定義")
            continue

        offset_tc = CASE_OFFSETS[case_num]
        offset_frames = tc_to_frames(offset_tc, fps)
        rel_frames = tc_to_frames(rel_tc, fps)
        abs_frames = offset_frames + rel_frames
        abs_tc = frames_to_tc(abs_frames, fps)

        marker_name = f"C{case_num}: {name[:30]}"

        if dry_run:
            print(f"  {abs_tc}  {marker_name}  |  {note[:60]}")
        else:
            frame_id = abs_frames - start_frames

            if frame_id < 0:
                errors.append(f"フレームが負: {abs_tc} (Case{case_num} {rel_tc})")
                continue

            result = timeline.AddMarker(
                frame_id,
                color,
                marker_name,
                note,
                1
            )
            if result:
                marker_count += 1
                print(f"  ✓ {abs_tc}  {marker_name}")
            else:
                errors.append(f"マーカー追加失敗: {abs_tc} {marker_name}")

    if not dry_run:
        print(f"\n--- 完了: {marker_count} マーカー追加 ---")
    else:
        print(f"\n--- dry-run完了: {len(ANNOTATIONS)} 件 ---")
    if errors:
        print(f"--- エラー: {len(errors)} 件 ---")
        for e in errors:
            print(f"  ! {e}")


def main():
    parser = argparse.ArgumentParser(description="注釈マーカー挿入")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--color", default="Green")
    parser.add_argument("--fps", type=float, default=0)
    args = parser.parse_args()
    run(dry_run=args.dry_run, color=args.color, fps=args.fps)


if __name__ == "__main__":
    main()
