# TC ユーティリティ
# ---------------------------------------------------------------------------
def tc_to_frames(tc_str, fps):
    """HH:MM:SS:FF → total frames"""
    parts = tc_str.replace(";", ":").split(":")
    parts = [int(p) for p in parts]
    if len(parts) == 4:
        h, m, s, f = parts
    elif len(parts) == 3:
        h, m, s = parts
        f = 0
    elif len(parts) == 2:
        h = 0
        m, s = parts
        f = 0
    else:
        return 0
    return int(((h * 3600 + m * 60 + s) * fps) + f)


def frames_to_tc(total_frames, fps):
    """total frames → HH:MM:SS:FF"""
    fps_int = int(round(fps))
    f = total_frames % fps_int
    total_seconds = total_frames // fps_int
    s = total_seconds % 60
    total_minutes = total_seconds // 60
    m = total_minutes % 60
    h = total_minutes // 60
    return f"{h:02d}:{m:02d}:{s:02d}:{f:02d}"


